-- Mesma modelagem que o Hibernate cria com ddl-auto=update.
-- Útil para ler o banco no SQL Editor do Supabase.

create table if not exists usuarios (
    id bigint generated by default as identity primary key,
    usuario varchar(40) not null unique,
    senha varchar(255) not null,
    nome varchar(120) not null,
    papel varchar(20) not null,
    tipo_agente varchar(20)
);

create table if not exists clientes (
    id bigint generated by default as identity primary key,
    usuario_id bigint not null unique references usuarios (id),
    rg varchar(20) not null,
    cpf varchar(11) not null unique,
    nome varchar(120) not null,
    endereco varchar(200) not null,
    profissao varchar(80) not null
);

create table if not exists empregadores (
    id bigint generated by default as identity primary key,
    cliente_id bigint not null references clientes (id),
    entidade varchar(120) not null,
    rendimento numeric(12, 2) not null
);

create table if not exists agentes (
    id bigint generated by default as identity primary key,
    usuario_id bigint not null unique references usuarios (id),
    tipo varchar(20) not null,
    nome varchar(120) not null,
    razao_social varchar(160) not null
);

create table if not exists automoveis (
    id bigint generated by default as identity primary key,
    matricula varchar(20) not null unique,
    ano integer not null,
    marca varchar(60) not null,
    modelo varchar(60) not null,
    placa varchar(8) not null unique,
    tipo_proprietario varchar(20) not null,
    proprietario_cliente_id bigint references clientes (id),
    proprietario_agente_id bigint references agentes (id)
);

create table if not exists pedidos (
    id bigint generated by default as identity primary key,
    cliente_id bigint not null references clientes (id),
    automovel_id bigint not null references automoveis (id),
    data_inicio date not null,
    data_fim date not null,
    valor_diaria numeric(12, 2) not null,
    valor_total numeric(12, 2) not null,
    status varchar(30) not null,
    observacao varchar(400),
    parecer varchar(500),
    agente_avaliador_id bigint references agentes (id),
    criado_em timestamp not null
);

create table if not exists contratos_credito (
    id bigint generated by default as identity primary key,
    pedido_id bigint not null unique references pedidos (id),
    banco_id bigint not null references agentes (id),
    valor_financiado numeric(12, 2) not null,
    numero_parcelas integer not null,
    taxa_mensal numeric(5, 2) not null,
    concedido_em date not null
);
